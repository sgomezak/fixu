// Generates supabase/seed/holidays.sql from data/holidays/*.json (idempotent upsert).
// Usage: node scripts/seed-holidays.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const q = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const rows = [];
for (const f of readdirSync('data/holidays').filter((f) => f.endsWith('.json')).sort()) {
  const data = JSON.parse(readFileSync(`data/holidays/${f}`, 'utf8'));
  for (const h of data.holidays) {
    rows.push(`(${q(h.date)}, ${q(h.name)}, ${q(h.scope)}, ${q(h.source.name)}, ${q(h.source.url)}, ${h.provisional ? 'true' : 'false'})`);
  }
}
mkdirSync('supabase/seed', { recursive: true });
writeFileSync(
  'supabase/seed/holidays.sql',
  `-- Generated by scripts/seed-holidays.mjs from data/holidays. Do not edit by hand.
insert into public.holidays (date, name, scope, source_name, source_url, provisional) values
${rows.join(',\n')}
on conflict (coalesce(user_id, '00000000-0000-0000-0000-000000000000'::uuid), date, scope, name)
do update set source_name = excluded.source_name, source_url = excluded.source_url, provisional = excluded.provisional;
`,
);
console.log(`${rows.length} holidays written`);
